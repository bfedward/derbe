CREATE TABLE public.employees (
    unid                             uuid                             DEFAULT gen_random_uuid() NOT NULL,
    first_name                       character varying                NOT NULL,
    last_name                        character varying                NOT NULL,
    job_title                        character varying                NOT NULL,
    email                            text                             NOT NULL,
    password                         text                             NOT NULL,
    role                             text                             DEFAULT 'RegularUser'::text NOT NULL,
    division_id                      integer                          NOT NULL,
    employment_type                  public.valid_employment_types    NOT NULL,
    location_id                      integer                          NOT NULL,
    manager_unid                     uuid,
    email_verified_at                timestamp with time zone,
    last_login_at                    timestamp with time zone,
    deleted_at                       timestamp with time zone,
    email_change_pending             text,
    email_change_token               text,
    email_change_token_expires_at    timestamp with time zone,
    created_at                       timestamp with time zone         DEFAULT now() NOT NULL,
    updated_at                       timestamp with time zone         DEFAULT now() NOT NULL,
    CONSTRAINT employees_pkey PRIMARY KEY (unid),
    CONSTRAINT employees_email_change_token_key UNIQUE (email_change_token),
    CONSTRAINT employees_email_check CHECK ((email = lower(email))),
    CONSTRAINT employees_email_change_pending_check CHECK (((email_change_pending IS NULL) OR (email_change_pending = lower(email_change_pending)))),
    CONSTRAINT employees_role_check CHECK ((role = ANY (ARRAY['Admin'::text, 'Manager'::text, 'RegularUser'::text, 'Demo'::text]))),
    CONSTRAINT employee_cant_manage_self CHECK ((manager_unid <> unid)),
    CONSTRAINT fk_employees_division_id FOREIGN KEY (division_id) REFERENCES public.divisions(id),
    CONSTRAINT fk_employees_location_id FOREIGN KEY (location_id) REFERENCES public.locations(id),
    CONSTRAINT fk_employees_manager_unid FOREIGN KEY (manager_unid) REFERENCES public.employees(unid)
);
